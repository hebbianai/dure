fn normalize_whitespace(declaration: String) -> String {
    declaration
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
}

fn optional_fields(mut declaration: String, fields: &[&str]) -> String {
    for field in fields {
        let required = format!("{field}: ");
        let optional = format!("{field}?: ");
        assert!(
            declaration.contains(&required),
            "generated declaration is missing expected field {field}"
        );
        declaration = declaration.replacen(&required, &optional, 1);
    }
    declaration
}
