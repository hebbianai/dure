// Pure assembly of the feedback wire envelope
// (crates/dure-feedback-intake/src/wire.rs's `Submission`). No I/O and no
// `process`/`Date`/`crypto` reads here: every value that could vary at
// runtime arrives as an argument, so this module cannot drift from the wire
// it targets and stays fully testable without mocking anything.
//
// Deliberately duplicates the wire's shape rather than importing
// src/lib/feedback/envelope.ts — the CLI ships as its own npm package
// (cli/package.json's "files" never includes src/), so this module is the
// CLI's own copy of the contract, kept honest by scripts/wire.rs-derived
// tests rather than a shared import.

/** Default intake endpoint. Overridable by the I/O half via
 *  `DURE_FEEDBACK_ENDPOINT` — read there, never here, so this module never
 *  touches `process.env`. */
export const FEEDBACK_ENDPOINT_DEFAULT = "https://dure-feedback.fly.dev/v1/feedback";

/** The kinds the wire accepts (wire.rs's `Kind` enum, lowercase on the
 *  wire). The CLI's own `--kind` flag exposes only "bug"/"idea"/"other" —
 *  "crash" is reserved for automated crash reporting, not something a
 *  person composing a report by hand should pick — but this pure builder
 *  accepts all four so it stays the one place that mirrors the wire. */
export const FEEDBACK_KINDS = Object.freeze(["bug", "idea", "other", "crash"]);

/** Caps this module knows about, copied from
 *  crates/dure-feedback-intake/src/wire.rs so the numbers can never drift by
 *  hand-retyping them. `BODY_LIMIT` and `CONTACT_LIMIT` are enforced here —
 *  the app learned the hard way that a client-side cap that disagrees with
 *  the server's produces an unexplainable 413, and the app's own
 *  `FeedbackDialog.tsx` already caps contact client-side for the same
 *  reason. `ENV_FIELD_LIMIT` is not locally enforced: every env value is
 *  machine-generated by this CLI itself, never typed by a person, so there
 *  is no realistic path to exceeding it. Every cap is recorded here so a
 *  future local check for one starts from the same number instead of
 *  guessing; the server remains the source of truth for all of them. */
export const FEEDBACK_BODY_LIMIT = 8_000;
export const FEEDBACK_CONTACT_LIMIT = 200;
export const FEEDBACK_ENV_FIELD_LIMIT = 200;
export const FEEDBACK_DEVICE_LIMIT = 128;

/** wire.rs's own device charset — client-generated, so legitimate values
 *  are always exactly this shape. Used both to accept a freshly generated
 *  id and to detect a corrupted persisted one (see
 *  feedback-command.mjs's `loadOrCreateFeedbackDeviceId`). */
const DEVICE_CHARSET = /^[A-Za-z0-9._:-]+$/;

export function isValidFeedbackDevice(value) {
	return (
		typeof value === "string" &&
		value.length > 0 &&
		value.length <= FEEDBACK_DEVICE_LIMIT &&
		DEVICE_CHARSET.test(value)
	);
}

export class FeedbackEnvelopeError extends Error {
	constructor(message) {
		super(message);
		this.name = "FeedbackEnvelopeError";
	}
}

/** Unicode scalar value count — matches Rust's `str::chars().count()`,
 *  which is what wire.rs's `BODY_LIMIT` check counts against. Plain
 *  `.length` counts UTF-16 code units instead, which would double-count
 *  every astral character (most emoji included) and reject valid reports
 *  under their real length. */
function scalarLength(value) {
	return Array.from(value).length;
}

const ENV_FIELD_NAMES = Object.freeze(["app", "channel", "os", "arch", "locale", "window"]);

/**
 * Builds the exact JSON object the intake accepts, or throws
 * `FeedbackEnvelopeError` with a message safe to print to the user.
 *
 * `contact` is trimmed and, when blank, omitted entirely rather than sent
 * as an empty string — the wire normalizes a blank contact to absent at its
 * own parse boundary, so sending nothing is simplest and matches what the
 * app's own `buildEnvelope` (src/lib/feedback/envelope.ts) does. A contact
 * over the wire's cap is refused locally, with the same message shape as
 * an oversized body.
 */
export function buildFeedbackEnvelope({ kind, body, contact, env, device }) {
	if (!FEEDBACK_KINDS.includes(kind)) {
		throw new FeedbackEnvelopeError(
			`Unknown feedback kind "${kind}". Use one of: ${FEEDBACK_KINDS.join(", ")}.`,
		);
	}
	if (typeof body !== "string" || body.trim().length === 0) {
		throw new FeedbackEnvelopeError("Feedback body must not be empty.");
	}
	const bodyLength = scalarLength(body);
	if (bodyLength > FEEDBACK_BODY_LIMIT) {
		throw new FeedbackEnvelopeError(
			`Feedback body is ${bodyLength} characters, over the ${FEEDBACK_BODY_LIMIT}-character limit.`,
		);
	}
	if (env === null || typeof env !== "object") {
		throw new FeedbackEnvelopeError("Feedback envelope requires env.");
	}
	for (const name of ENV_FIELD_NAMES) {
		if (typeof env[name] !== "string" || env[name].length === 0) {
			throw new FeedbackEnvelopeError(`Feedback env.${name} is required.`);
		}
	}
	if (typeof device !== "string" || device.length === 0) {
		throw new FeedbackEnvelopeError("Feedback device id is required.");
	}
	const trimmedContact = typeof contact === "string" ? contact.trim() : "";
	if (trimmedContact.length > 0) {
		const contactLength = scalarLength(trimmedContact);
		if (contactLength > FEEDBACK_CONTACT_LIMIT) {
			throw new FeedbackEnvelopeError(
				`Feedback contact is ${contactLength} characters, over the ${FEEDBACK_CONTACT_LIMIT}-character limit.`,
			);
		}
	}
	return {
		schema: 1,
		kind,
		body,
		...(trimmedContact.length > 0 ? { contact: trimmedContact } : {}),
		env: {
			app: env.app,
			channel: env.channel,
			os: env.os,
			arch: env.arch,
			locale: env.locale,
			window: env.window,
		},
		device,
		attachments: [],
	};
}
