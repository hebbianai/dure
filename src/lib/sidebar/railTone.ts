/** 액티비티 레일 아이콘 버튼의 표면 클래스 — Figma "라이트 버전" 2039:27854 (Menu).
 *
 *  리디자인이 바꾼 건 활성 표시 방식이다. 예전에는 VS Code식 왼쪽 인디케이터
 *  막대였는데, 디자인의 활성 항목은 레일 표면에서 한 단 떠오른 "칩"이다 —
 *  pane 색 배경 + pane 테두리 + pane 그림자. 막대는 레일 밖으로 삐져나온
 *  장식이라 표면이 유리처럼 반투명해지면 걸 곳이 없어진다. 칩은 표면 자체가
 *  신호라서 그 문제가 없다.
 *
 *  토큰으로만 쓰는 이유는 다크 대응이다. --glass-pane은 라이트에서 흰색,
 *  다크에서 --card와 같은 높이의 밝은 회색이라, "배경보다 한 단 위" 라는
 *  같은 위계가 두 모드에서 그대로 성립한다. 흰색을 직접 박으면 다크에서
 *  레일만 하얗게 뜬다.
 *
 *  비활성 항목은 표면이 없다. 호버에서만 --glass-tint-hover가 얹히는데,
 *  이 토큰은 (불투명 회색이 아니라) 낮은 알파의 틴트라서 뒤에 어떤 표면이
 *  오든 같은 세기로 얹힌다.
 *
 *  글리프 색은 활성/비활성이 같은 --foreground다. 시안에서 내보낸 아이콘
 *  에셋의 stroke를 직접 확인한 값이다 — 라이트(2070:32039) 전부 #0A0A0A,
 *  다크(2072:33537) 전부 #FAFAFA로, 비활성 아이콘(폴더·설정)도 예외가 없다.
 *  #0A0A0A/#FAFAFA는 --foreground(=--sidebar-foreground)이지
 *  --muted-foreground(#737373)가 아니다. muted는 이 시안에서 배지 닷 하나에만
 *  쓰인다.
 *
 *  비활성을 muted로 흐리게 칠하던 예전 값은 아이콘 전체를 시안보다 연하게
 *  만들었다 (사용자 지적, 2026-07-31). 선택 여부는 색이 아니라 칩 표면이
 *  말한다 — 색까지 같이 쓰면 신호가 둘로 갈려 어느 쪽이 선택인지 흐려진다.
 *
 *  크기·모서리(36px / 8px)와 아이콘 16px은 디자인 값 그대로다. rounded-md가
 *  정확히 8px이다(--radius 10px * 0.8) — rounded-lg는 10px이라 디자인과 2px
 *  어긋난다.
 *
 *  dark:bg-secondary는 다크 전용 보정이다. 라이트에서 칩은 #ffffff가 #fafafa
 *  위에 5/255만 떠 있고 나머지는 그림자가 감당하는데, 그 그림자는 순수 검정
 *  드롭섀도라 near-black 표면 위에서는 사실상 보이지 않는다. 다크에서 같은
 *  단차만 남기면 "떠 있다"는 신호가 통째로 사라지므로, 그림자가 못 하는 몫을
 *  채도 없는 한 단 밝은 표면이 대신한다.
 *
 *  칩은 사이드바가 접혀도 그대로다. 예전에는 접히면 --background로 한 단
 *  내려 "셸을 뚫은 창"처럼 보이게 했는데, 실제 화면에서는 그게 접을 때마다
 *  아이콘 배경만 눈에 띄게 어두워지는 깜빡임으로 읽혔다 (사용자 지적,
 *  2026-07-31). 시안도 활성 표시를 하나만 정의한다 — 2070:32039(라이트)와
 *  2072:33537(다크) 어느 쪽에도 접힘 전용 변형이 없다.
 *
 *  접힘/펼침으로 갈라야 할 것 같았던 이유는 "칩이 무엇과 짝을 이루는가"였다.
 *  하지만 짝이 없어졌다는 사실은 패널이 사라진 것으로 이미 보이고, 칩까지
 *  같이 움직이면 한 동작에 두 군데가 바뀌어 어느 쪽이 신호인지 흐려진다. */
export function railItemSurface(active: boolean): string {
  if (!active) {
    // 비활성 아이콘의 stroke는 보조 텍스트 색이다(소유자 결정, 2026-08-02).
    // 시안(2070:32039 라이트 #0A0A0A / 2072:33537 다크 #FAFAFA)은 비활성도
    // foreground로 내보내지만, 활성 칩이 흰 카드에서 파인 틴트로 바뀌면서
    // (2026-08-01) 표면만으로는 선택이 약하게 읽힌다 — 아이콘 색까지 같으면
    // 활성/비활성을 가르는 신호가 틴트 하나뿐이다. 색을 한 단 낮춰 그 위계를
    // 아이콘에도 싣는다. "시안대로" foreground로 되돌리지 말 것.
    //
    // 호버에서는 foreground로 돌아온다 — 틴트만 얹히고 글리프는 그대로면
    // 가리키는 대상이 반응하지 않는 것처럼 보인다.
    return "text-muted-foreground hover:bg-glass-tint-hover hover:text-sidebar-foreground";
  }
  // 활성 표시는 모드마다 다르다. 유리의 밝기가 어느 쪽이 읽히는지를 정하기
  // 때문이다: 라이트 유리는 233(거의 흰색)이라 9% 틴트를 얹어도 차이가 거의
  // 없지만 흰 면은 233 대 255로 확실히 갈린다. 다크 유리는 어두워서 흰 면이
  // 박히면 튀고, 밝은 틴트가 자연스럽다.
  //
  // 2026-08-01에 흰 면을 걷어낸 적이 있는데, 문제는 흰 면이 아니라 함께 있던
  // shadow-pane이었다 — 그림자가 "떠 있는 카드"를 "웹앱 버튼"으로 만든다.
  // 네이티브 앱의 선택 카드도 그림자 없이 헤어라인 하나뿐이다. 그래서 라이트는
  // 흰 면 + 헤어라인(그림자 없음), 다크는 틴트로 간다.
  //
  // 라이트 흰 면은 불투명이 아니라 75%다. 셸에서 유리로 남는 면적이 사이드바
  // 뿐인데 선택 칩·행이 그걸 완전히 막으면 유리가 통째로 줄어든다(사용자 지적,
  // 2026-08-02). 75%면 밑 유리가 비치면서도 233 대 250으로 선택은 그대로 읽힌다.
  //
  // 링은 border가 아니라 inset-ring이다(v4 유틸리티 — v3의 ring-inset은 무효) —
  // 레일 칩은 36px 고정이라 테두리를 주면
  // 안쪽 글리프 자리가 1px씩 줄어든다.
  return [
    "text-sidebar-foreground",
    "bg-glass-pane/75 inset-ring-1 inset-ring-glass-pane-border",
    "dark:bg-foreground/[0.13] dark:inset-ring-0",
  ].join(" ");
}

/** 활성/비활성이 공유하는 기하 — 호출 쪽에서 railItemSurface()와 함께 쓴다. */
export const RAIL_ITEM_BASE =
  "flex size-9 shrink-0 items-center justify-center rounded-md transition-colors";

/** 레일 아이콘 크기 — 디자인의 "Sidebar item icon" 16px. */
export const RAIL_ICON_SIZE = "size-4";
